const TABLES = { en: EN, hi: HI, te: TE };

/**
 * The string for `key` in the current language.
 * Falls back to English, then to the key itself — never to a blank, because a
 * missing translation should look like a bug, not like an empty screen.
 */
export function t(key, vars) {
  const table = TABLES[current] || EN;
  let s = table[key];
  if (s == null) s = EN[key];
  if (s == null) return key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

/* A CATEGORY'S NAME IN THE READER'S LANGUAGE. The engine's `cat.name` is the
   English source of truth and stays that way; this is what a SCREEN prints.
   Written as `cat.` + id, so a category added to the catalogue without a key
   falls back to its English name rather than showing a key — and
   tools/lint-i18n.mjs knows the whole `cat.` family is rendered here. */
/* A JOB NAME IN THE READER'S LANGUAGE, the same way `catName` does a category.
   `domain/catalog.services.js` owns the English source of truth and the stable
   id; this prints what a SCREEN should show. A job with no key yet falls back to
   its English name rather than painting a key at a customer. */
export const subName = (name, key) => {
  if (!name) return '';
  if (!key) return name;
  const got = t('sub.' + key);
  return got === 'sub.' + key ? name : got;
};

/* THE ONLY LANGUAGE PICKER IN THE APP WAS ON THE CUSTOMER'S ACCOUNT SCREEN.
   Not on the landing page, not in pro signup, not in any of the seven
   onboarding steps, not in the pro console, not in the shop console. A
   Telugu-only plumber who taps "I offer a service" cannot reach it: the whole
   partner side is behind a door he has no way to translate. An audit had to
   use `?lang=te`, which nobody types.

   This is the markup, once, so every surface can carry the same control. It
   builds a string and touches no DOM, like the accessors below it.
   No escaping here: every value is a fixed constant from LANGS or the table,
   never anything a person typed, and importing ui/dom.js would invert the
   layering (dom.js reads this module). */
export function langPicker(opts = {}) {
  const chips = LANGS.map(l => `<button class="chip${current === l.id ? ' on' : ''}"
      data-act="lang.set" data-lang="${l.id}" lang="${l.id}">${l.native}</button>`).join('');
  return `<div style="padding:${opts.tight ? '6px 0' : '10px 0'}">
    ${opts.tight ? '' : `<div class="m-cap" style="margin:0 0 6px">${t('lang.pick')}</div>`}
    <div class="chiprow" style="flex-wrap:wrap">${chips}</div>
    ${unreviewed() ? `<p class="micro muted" style="margin-top:6px">${t('lang.unreviewed')}</p>` : ''}
  </div>`;
}

export const catName = c =>
  !c ? '' : (t('cat.' + c.id) === 'cat.' + c.id ? (c.name || '') : t('cat.' + c.id));

/** Every key that has no translation in the given language — for docs/I18N.md. */
export function missing(id = current) {
  const table = TABLES[id] || {};
  return Object.keys(EN).filter(k => table[k] == null);
}

